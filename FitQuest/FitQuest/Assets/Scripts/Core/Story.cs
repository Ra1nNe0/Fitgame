    /// Одна реплика катсцены. Who: hero (выбранный герой), ally (второй герой), pulse или босс.
    /// KnightText — вариант на случай, когда героем выбран Рыцарь (тогда союзник — Король).
    /// </summary>
    public class StoryLine
    {
        public string Who;
        public string Mood;      // normal, happy, angry (у Пульса — worried вместо angry)
        public string Text;
        public string KnightText;

        public StoryLine(string who, string mood, string text, string knightText = null)
        {
            Who = who;
            Mood = mood;
            Text = text;
            KnightText = knightText;
        }
    }

