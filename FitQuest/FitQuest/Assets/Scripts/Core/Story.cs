        static List<string> Seen { get { return SaveData.Current.seenScenes; } }

        /// <summary>Катсцена, которую ещё не показывали, или null.</summary>
        public static StoryLine[] Unseen(string id)
        {
            StoryLine[] lines;
            if (!Scenes.TryGetValue(id, out lines) || Seen.Contains(id)) return null;
            return lines;
        }

        public static void MarkSeen(string id)
        {
            if (Seen.Contains(id)) return;
            Seen.Add(id);
            SaveData.Save();
        }

        // ------------------------------------------------------------------ кто говорит

        public static string HeroSkin { get { return SaveData.Current.skin == "knight" ? "knight" : "king"; } }

        /// <summary>Чей портрет: hero и ally превращаются в king или knight.</summary>
        public static string Portrait(string who)
        {
            if (who == "hero") return HeroSkin;
            if (who == "ally") return HeroSkin == "king" ? "knight" : "king";
            return who;
        }

        public static string SpeakerName(string who)
        {
            switch (Portrait(who))
            {
                case "king": return "КОРОЛЬ";
                case "knight": return "РЫЦАРЬ ЛИРА";
                case "pulse": return "ПУЛЬС";
                case "slime": return "КОРОЛЬ СЛИЗНЕЙ";
                case "bat": return "КОРОЛЕВА МЫШЕЙ";
                case "golem": return "МАГМОВЫЙ ГОЛЕМ";
                case "sloth": return "ЛОРД ЛЕНЬ";
            }
            return who.ToUpper();
        }

        /// <summary>Герои и Пульс стоят слева, противники — справа.</summary>
        public static bool OnLeft(string who) { return who == "hero" || who == "ally" || who == "pulse"; }

        public static string TextFor(StoryLine line)
        {
            return HeroSkin == "knight" && line.KnightText != null ? line.KnightText : line.Text;
        }

        public static string PortraitSprite(StoryLine line)
        {
            string who = Portrait(line.Who);
            string mood = line.Mood;
            // у каждого портрета свой набор эмоций — подбираем ближайшую
            if (who == "pulse") { if (mood == "angry") mood = "worried"; }
            else if (who == "king" || who == "knight") { if (mood == "worried") mood = "normal"; }
            else if (mood != "angry") mood = "normal";
            return "portrait_" + who + "_" + mood;
        }
